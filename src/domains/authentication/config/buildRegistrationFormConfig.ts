import { formFieldFactory } from '@/components/forms/utils/FormFieldFactory';
import type { FormConfig, FormFieldConfig, FormLabelConfig } from '@/components/forms/types/formConfig.types';
import { modelRegistry } from '@/core/models/ModelRegistry';
import { string, boolean, object, ref, type ObjectSchema } from 'yup';
import type yup from '@/core/validation/yup/yupExtensions';
import { registrationService } from '@/domains/authentication/services/registration.service';
import type { AutocompleteOption } from '@/components/ui';

/**
 * Registration Form Configuration Builder
 *
 * Config-driven single-page registration form combining fields from the
 * identity backend model, plus virtual companyName, countryId and
 * acknowledgedTerms fields.
 *
 * **Form fields:**
 * - firstname, lastname (identity)
 * - email, password, passwordConfirm (identity + UI-only)
 * - companyName (virtual — maps to company.name in payload)
 * - countryId (virtual — the account's jurisdiction, sent at the top level of the payload)
 * - acknowledgedTerms (virtual — consent, sent at the top level of the payload)
 *
 * Handle is auto-generated by the backend — not collected here.
 *
 * countryId is a constrained autocomplete whose options are the public country
 * catalog. Option values are country IDs; option labels come from the catalog,
 * which is already localised by the backend.
 *
 * @param countryOptions - Pre-loaded country options for the countryId autocomplete.
 * @param defaults - Optional existing values to pre-populate fields.
 * @returns FormConfig ready to pass to BaseFormRenderer.
 */
export function buildRegistrationFormConfig(
    countryOptions: AutocompleteOption[],
    defaults?: Record<string, unknown>
): FormConfig
{
    const presetValues = defaults ?? {};

    const allIdentityFields = formFieldFactory.getFormFields( 'identity' );

    const personalFields = allIdentityFields
        .filter( f => ['firstname', 'lastname'].includes( f.name ) );

    const accessFields = allIdentityFields
        .filter( f => ['email', 'password'].includes( f.name ) );

    // Consent, collected here and sent at the top level of the registration payload.
    // Declared locally rather than read from signupAttempt: that model exists to track
    // signups, not to collect them, and it stays off the public definition whitelist.
    // The backend validates it authoritatively on POST.
    const verifyFields: FormFieldConfig[] = [
        {
            name: 'acknowledgedTerms',
            type: 'checkbox',
            required: true,
            virtual: true,
        }
    ];

    // UI-only field: password confirmation (not in backend model)
    const passwordConfirm: FormFieldConfig = {
        name: 'passwordConfirm',
        type: 'password',
        required: true,
        virtual: true,
    };

    // Virtual field: company name (mapped to company.name in service payload)
    const companyName: FormFieldConfig = {
        name: 'companyName',
        type: 'text',
        required: true,
        virtual: true,
    };

    // Virtual field: the account's jurisdiction, sent at the top level of the payload.
    //
    // Type-ahead over the whole catalog, like the company field, but constrained: a country
    // outside the supported list is not a jurisdiction an account can be bound to. The
    // catalog is small and already loaded, so it filters locally rather than per keystroke.
    const country: FormFieldConfig = {
        name: 'countryId',
        type: 'autocomplete',
        freeSolo: false,
        required: true,
        virtual: true,
        options: countryOptions,
        defaultValue: presetValues['countryId'],
    };

    const enrichedVerifyFields = enrichVerificationFields( verifyFields );

    const allFormFields = [
        ...personalFields,
        ...accessFields,
        ...verifyFields,
    ];

    return {
        title: 'pages.registration.title',
        subtitle: 'pages.registration.subtitle',
        context: {
            isCreate: true,
            service: 'identity',
            operation: 'create',
            regionCode: 'global'
        },
        groups: [
            {
                type: 'fields',
                title: '',
                fields: [
                    ...personalFields,
                    companyName,
                    country,
                    ...accessFields,
                    passwordConfirm,
                    ...enrichedVerifyFields,
                ]
            }
        ],
        validationSchema: buildRegistrationYupSchema( allFormFields ),
        footerLink: {
            prefaceText: 'pages.registration.alreadyHaveAccount',
            href: '/auth/login',
            linkText: 'shared.buttons.login'
        }
    };
}

/**
 * Enriches consent fields with custom label configurations.
 *
 * Adds a clickable Terms & Conditions link to the acknowledgedTerms checkbox label.
 *
 * @param fields - Consent fields collected by this form
 * @returns Fields with FormLabelConfig for rich label rendering
 */
function enrichVerificationFields( fields: FormFieldConfig[] ): FormFieldConfig[]
{
    return fields.map( field =>
    {
        if( field.name === 'acknowledgedTerms' )
        {
            return {
                ...field,
                label: {
                    text: 'forms.registration.fields.acknowledgedTerms',
                    link: 'forms.registration.fields.acknowledgedTermsLink',
                    href: '/terms'
                } as FormLabelConfig
            };
        }

        return field;
    } );
}

/**
 * Builds the combined Yup validation schema for registration.
 *
 * Merges validation from backend models and adds frontend-only rules
 * (passwordConfirm cross-field match, companyName required string).
 *
 * @param formFields - Fields rendered in the form
 * @returns Combined Yup schema for react-hook-form
 */
function buildRegistrationYupSchema(
    formFields: FormFieldConfig[]
): ObjectSchema<any>  
{
    const identitySchema = modelRegistry.getValidation( 'identity' );

    const fieldNames = formFields.map( f => f.name );

    const identityFields = Object.entries( identitySchema.fields )
        .filter( ( [key] ) => fieldNames.includes( key ) );

    const mergedValidation: Record<string, yup.AnySchema> = {
        ...Object.fromEntries( identityFields ),
        passwordConfirm: string()
            .required()
            .oneOf( [ref( 'password' )] ),
        companyName: string()
            .required()
            .min( 1 )
            .max( 255 ),
        countryId: string()
            .required()
            .uuid(),
        acknowledgedTerms: boolean()
            .required()
            .mustAccept(),
    };

    if( mergedValidation.email )
    {
        const emailSchema = mergedValidation.email as yup.StringSchema;

        mergedValidation.email = emailSchema.isUnique(
            async ( email: string ) =>
            {
                const res = await registrationService.checkEmail( email );
                return res.status === 204;
            }
        );
    }

    return object().shape( mergedValidation );
}
